"""
09.荷物検査
あなたは空港の手荷物検査を受けるところです。検査では手荷物の重量が測定され、合計が基準値を超えていると飛行機に乗ることができません。
手荷物の個数 N、重さの基準値 M、i 番目の荷物の重さ A_i (1 ≦ i ≦ N) が与えられるので、荷物の総重量が基準値以下であれば "OK"、基準値より大きければ "NG" を出力してください。
"""
N,M = map(int, input().split())
A = [0,]
for i in range(1, N+1):
    A.append(int(input()))
if sum(A) > M:
    print("NG")
else:
    print("OK")
